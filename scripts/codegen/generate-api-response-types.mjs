/**
 * Generates TypeScript from JSON response samples using @clyf/core's generateTypeFromJson.
 *
 * Docs: https://www.npmjs.com/package/@clyf/core
 *
 * 1. Put representative API JSON under scripts/codegen/json-samples/*.json
 * 2. pnpm install
 * 3. pnpm codegen:api-types
 *
 * If generation fails, open this file and adjust `callGenerateTypeFromJson` to match
 * the exact signature / options your @clyf/core version exports.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..', '..');
const SAMPLES_DIR = path.join(__dirname, 'json-samples');
const OUT_FILE = path.join(REPO_ROOT, 'src', 'generated', 'api-response-types.ts');

function pascalFromJsonFilename(filename) {
  const base = path.basename(filename, '.json');
  return base
    .replace(/\.sample$/i, '')
    .split(/[-_.]+/)
    .filter(Boolean)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('');
}

function normalizeGenerated(result) {
  if (typeof result === 'string') {
    return result;
  }
  if (result && typeof result === 'object') {
    for (const key of ['typescript', 'ts', 'code', 'output']) {
      if (typeof result[key] === 'string') {
        return result[key];
      }
    }
  }
  throw new TypeError(
    `generateTypeFromJson returned unexpected type: ${typeof result}. Adjust normalizeGenerated() in generate-api-response-types.mjs`,
  );
}

async function loadGenerateTypeFromJson() {
  const mod = await import('@clyf/core');
  const fn = mod.generateTypeFromJson ?? mod.default?.generateTypeFromJson;
  if (typeof fn !== 'function') {
    throw new Error(
      '@clyf/core: expected a generateTypeFromJson export. Check the package README for the current API.',
    );
  }
  return fn;
}

async function main() {
  const generateTypeFromJson = await loadGenerateTypeFromJson();

  const files = fs
    .readdirSync(SAMPLES_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort();

  if (files.length === 0) {
    console.error('No .json files in', SAMPLES_DIR);
    process.exit(1);
  }

  const chunks = [
    '/* eslint-disable */',
    '/**',
    ' * Generated by `pnpm codegen:api-types` — do not edit by hand.',
    ' * Source samples: scripts/codegen/json-samples/',
    ' */',
    '',
  ];

  for (const file of files) {
    const jsonPath = path.join(SAMPLES_DIR, file);
    const typeName = pascalFromJsonFilename(file);
    const json = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    // Match @clyf/core docs for generateTypeFromJson(json, options?)
    const raw = generateTypeFromJson(json, { typeName });
    const ts = normalizeGenerated(raw);

    chunks.push(`// --- from ${file} (root type: ${typeName}) ---`);
    chunks.push(ts.trim());
    chunks.push('');
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, `${chunks.join('\n')}\n`, 'utf8');
  console.log('Wrote', path.relative(REPO_ROOT, OUT_FILE));
}

await main();
